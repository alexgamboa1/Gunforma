-- creator_invites: claimable creator pages that stay hidden until the creator says yes.
--
-- APPLY ONLY AFTER THE PAGES AND THE creator-claim EDGE FUNCTION ARE LIVE
-- (CLAUDE.md, "Branches and PRs": code first, then migration). Nothing on the
-- site calls anything here until an invite exists, and an invite can only be
-- made by scripts/creator-invites.js with the service-role key, so the code
-- can ship first and sit idle.
--
-- WHAT IT IS FOR. gunforma prepares a creator's page before asking them:
-- their builds, a short bio, their Instagram/YouTube links, and their handle
-- held so nobody else can take it. Then one DM carries a private link. The
-- creator sees the page, and either claims it (it goes live under their
-- name) or says "not interested" (the drafts are deleted). Until one of
-- those happens NOTHING IS PUBLIC:
--
--   * the builds are status 'draft' with no owner. "Public can view approved
--     builds" and "Public can view photos of approved builds" already hide
--     them, so /b/<id>, the gallery, the sitemap and the profile page never
--     see them. No policy changes here.
--   * the handle has no profiles row, so /u/<handle> is profile-og's normal
--     404. It does not say "reserved": that would announce that pages are
--     being prepared for people who have not agreed to anything.
--   * creator_invites itself is deny-all (RLS on, no policies, grants
--     revoked), the same pattern as claim_invites and price_history. Only
--     the service role reads it: scripts/creator-invites.js and the
--     creator-claim Edge Function.
--
-- WHY NOT claim_invites. That table is for a builder whose account is
-- created up front from an email address they gave us (launch-invite). A
-- creator we have only DMed has no email and no account, and must not get
-- one until they choose to. Different credential, different lifecycle.
--
-- THE CREDENTIAL. A 32-byte random token, base64url, generated by the
-- script and placed only in the DM'd URL. Only its sha256 hex is stored
-- (token_hash), exactly as claim_invites does it. "New link" overwrites the
-- hash, so an older link stops working the moment a new one exists.
--
-- STATUSES
--   invited   link out, nothing public, handle held
--   claimed   creator signed in and accepted; builds live under their account
--   declined  creator said no; drafts deleted, bio/links wiped, handle still
--             held so nobody else can pose as them (released only by revoke)
--   revoked   gunforma withdrew it; handle released, drafts left for the
--             admin to delete or reuse
--
-- WHAT ELSE CHANGES, and why each one is needed:
--
--   1. prevent_build_consent_tampering() admits is_trusted_backend(). The
--      claim writes the creator's consent onto builds that were saved
--      without it, and it runs as the service role. The guard only
--      admitted is_admin(), which reads auth.uid(), which is NULL for the
--      service role, so the guard refused the most trusted caller there is:
--      CLAUDE.md, "service_role bypasses RLS. It does not bypass triggers."
--      Nothing else is widened. An owner still cannot touch consent fields.
--
--   2. A trigger on profiles refuses a username that matches a held handle
--      (case-insensitively), raising 23505 so every page that already
--      handles "that username was just taken" handles this too, without
--      learning anything it should not. The claim marks the invite claimed
--      BEFORE it writes the username, so the claim itself passes.
--
--   3. username_is_held(text) lets the four username checkers (signup,
--      complete-profile, claim, account) show "Taken" up front instead of
--      failing at submit. It answers one boolean for one exact name; it
--      cannot list anything.
--
-- Rollback: drop the three functions, the trigger, the two tables, and
-- restore the guard's body from the baseline (is_admin() only).

-- ── tables ──────────────────────────────────────────────────────────────

create table public.creator_invites (
  id            uuid primary key default gen_random_uuid(),
  handle        text not null
                check (handle ~ '^[a-zA-Z0-9_]{3,24}$'),   -- profiles_username_check
  display_name  text check (display_name is null or length(display_name) <= 60),
  bio           text check (bio is null or length(bio) <= 280),
  instagram_url text check (instagram_url is null or instagram_url ~ '^https://(www\.)?instagram\.com/'),
  youtube_url   text check (youtube_url is null or youtube_url ~ '^https://(www\.|m\.)?youtube\.com/'),
  token_hash    text unique,                                 -- sha256 hex; never the raw token
  expires_at    timestamptz not null,
  status        text not null default 'invited'
                check (status in ('invited', 'claimed', 'declined', 'revoked')),
  sent_via      text,                                        -- where the link went, e.g. "IG DM from @gunforma"
  opened_at     timestamptz,                                 -- first preview load
  claimed_at    timestamptz,
  claimed_by    uuid references auth.users(id) on delete set null,
  declined_at   timestamptz,
  revoked_at    timestamptz,
  created_at    timestamptz not null default now(),
  updated_at    timestamptz not null default now(),
  constraint creator_invites_claimed_shape
    check ((status = 'claimed') = (claimed_at is not null))
);

comment on table public.creator_invites is
  'A creator page prepared before the creator agreed to anything. Hidden until claimed. Service-role only (RLS deny-all). Stores sha256(token) hex, never the raw token. See supabase/migrations/20261027040000_creator_invites.sql.';

-- One live invite per handle, case-insensitively. A revoked one releases it.
create unique index creator_invites_handle_live
  on public.creator_invites (lower(handle))
  where status <> 'revoked';

create table public.creator_invite_builds (
  invite_id uuid not null references public.creator_invites(id) on delete cascade,
  -- PRIMARY KEY on build_id alone: one build belongs to at most one invite.
  -- ON DELETE CASCADE: deleting a draft in the queue simply drops it from
  -- the invite instead of leaving a dangling row.
  build_id  uuid primary key references public.builds(id) on delete cascade,
  position  integer not null default 0
);

comment on table public.creator_invite_builds is
  'Which draft builds a creator invite carries. Service-role only (RLS deny-all).';

create index creator_invite_builds_invite_idx on public.creator_invite_builds (invite_id);

alter table public.creator_invites       enable row level security;
alter table public.creator_invite_builds enable row level security;
revoke all on public.creator_invites       from anon, authenticated;
revoke all on public.creator_invite_builds from anon, authenticated;

create trigger creator_invites_updated_at
  before update on public.creator_invites
  for each row execute function public.set_updated_at();

-- ── 1. consent guard admits the trusted backend ─────────────────────────

create or replace function public.prevent_build_consent_tampering()
returns trigger
language plpgsql
security definer
set search_path to 'public'
as $$
begin
  if (new.content_license_confirmed is distinct from old.content_license_confirmed
      or new.legal_confirmed is distinct from old.legal_confirmed
      or new.confirmed_at is distinct from old.confirmed_at
      or new.builder_agreement_version is distinct from old.builder_agreement_version)
     and not public.is_admin()
     -- 2026-10-27: the creator claim (claim_creator_invite, service role)
     -- writes the creator's own consent onto their draft builds.
     and not public.is_trusted_backend()
  then
    raise exception 'Consent fields cannot be edited after submission';
  end if;
  return new;
end;
$$;

-- ── 2 + 3. held handles ─────────────────────────────────────────────────

create or replace function public.username_is_held(p_username text)
returns boolean
language sql
stable
security definer
set search_path to ''
as $$
  select exists (
    select 1 from public.creator_invites ci
     where lower(ci.handle) = lower(btrim(p_username))
       and ci.status in ('invited', 'declined')
  );
$$;

comment on function public.username_is_held(text) is
  'True when this exact username (case-insensitive) is held for a creator invite. One name, one boolean: it cannot enumerate. Pages show "Taken", the same word as for an existing profile.';

revoke execute on function public.username_is_held(text) from public;
grant  execute on function public.username_is_held(text) to anon, authenticated, service_role;

create or replace function public.refuse_held_username()
returns trigger
language plpgsql
security definer
set search_path to ''
as $$
begin
  if new.username is not null
     and (tg_op = 'INSERT' or new.username is distinct from old.username)
     and public.username_is_held(new.username)
  then
    -- 23505 (unique_violation) on purpose: every username form already turns
    -- it into "That username was just taken", which is all a stranger should
    -- learn. GoTrue surfaces it on sign-up as a database error, which the
    -- sign-up page avoids by asking username_is_held() first.
    raise exception 'That username is taken.' using errcode = '23505';
  end if;
  return new;
end;
$$;

revoke execute on function public.refuse_held_username() from public, anon, authenticated;

create trigger trg_refuse_held_username
  before insert or update of username on public.profiles
  for each row execute function public.refuse_held_username();

-- ── the three things the Edge Function does ─────────────────────────────
-- All SECURITY INVOKER and executable by the service role only. Run as the
-- service role, every trigger on builds/profiles sees request.jwt.claims
-- role = service_role, which is what is_trusted_backend() and the photo and
-- role guards already admit. No new definer context, no new trap.

-- What the private page shows. Stamps opened_at the first time.
create or replace function public.creator_invite_preview(p_token_hash text)
returns jsonb
language plpgsql
set search_path to ''
as $$
declare
  v public.creator_invites;
  v_builds jsonb;
begin
  select * into v from public.creator_invites where token_hash = p_token_hash;
  if not found or v.status = 'revoked' then
    return jsonb_build_object('error', 'invalid');
  end if;
  if v.status = 'claimed' then
    return jsonb_build_object('error', 'already_claimed', 'handle', v.handle);
  end if;
  if v.status = 'declined' then
    return jsonb_build_object('error', 'declined');
  end if;
  if v.expires_at < now() then
    return jsonb_build_object('error', 'expired');
  end if;

  if v.opened_at is null then
    update public.creator_invites set opened_at = now() where id = v.id;
  end if;

  select coalesce(jsonb_agg(jsonb_build_object(
           'id',          b.id,
           'name',        b.name,
           'description', b.description,
           'activities',  to_jsonb(b.activities),
           'platform',    p.name,
           'part_count',  jsonb_array_length(b.parts_snapshot),
           'parts',       (select coalesce(jsonb_agg(jsonb_build_object(
                                     'category', e ->> 'category',
                                     'brand',    e ->> 'brand',
                                     'name',     e ->> 'name')), '[]'::jsonb)
                             from jsonb_array_elements(b.parts_snapshot) e),
           'photos',      (select coalesce(jsonb_agg(jsonb_build_object(
                                     'path',  ph.storage_path,
                                     'thumb', ph.thumb_path,
                                     'hero',  ph.is_hero)
                                   order by ph.is_hero desc, ph.position), '[]'::jsonb)
                             from public.build_photos ph where ph.build_id = b.id)
         ) order by cib.position, b.created_at), '[]'::jsonb)
    into v_builds
    from public.creator_invite_builds cib
    join public.builds b    on b.id = cib.build_id
    join public.platforms p on p.id = b.platform_id
   where cib.invite_id = v.id
     and b.status = 'draft' and b.user_id is null;

  return jsonb_build_object(
    'handle',        v.handle,
    'display_name',  v.display_name,
    'bio',           v.bio,
    'instagram_url', v.instagram_url,
    'youtube_url',   v.youtube_url,
    'expires_at',    v.expires_at,
    'builds',        v_builds
  );
end;
$$;

-- Claim: the creator's account takes the handle, the bio and links, and the
-- builds, which go live with the consent the creator just gave. One
-- transaction: either all of it happens or none of it does.
create or replace function public.claim_creator_invite(
  p_token_hash        text,
  p_user_id           uuid,
  p_agreement_version text
)
returns jsonb
language plpgsql
set search_path to ''
as $$
declare
  v public.creator_invites;
  v_build_ids uuid[];
  v_ready int;
  v_moved int;
begin
  if p_agreement_version is null or length(btrim(p_agreement_version)) = 0 then
    raise exception 'agreement version is required';
  end if;

  select * into v from public.creator_invites
   where token_hash = p_token_hash
   for update;
  if not found or v.status = 'revoked' then
    return jsonb_build_object('error', 'invalid');
  end if;
  if v.status = 'claimed' then
    return jsonb_build_object('error', 'already_claimed', 'handle', v.handle);
  end if;
  if v.status = 'declined' then
    return jsonb_build_object('error', 'declined');
  end if;
  if v.expires_at < now() then
    return jsonb_build_object('error', 'expired');
  end if;

  if not exists (select 1 from public.profiles where id = p_user_id) then
    return jsonb_build_object('error', 'no_profile');
  end if;

  -- Someone already has this handle in another case ("Name" vs "name").
  -- profiles' own unique constraint is case-sensitive, so ask here.
  if exists (select 1 from public.profiles
              where lower(username) = lower(v.handle) and id <> p_user_id) then
    return jsonb_build_object('error', 'handle_taken');
  end if;

  select coalesce(array_agg(cib.build_id order by cib.position), '{}')
    into v_build_ids
    from public.creator_invite_builds cib
   where cib.invite_id = v.id;

  -- Every build must still be an unowned draft. If the admin published or
  -- deleted one meanwhile, stop rather than hand over half a page.
  select count(*) into v_ready
    from public.builds b
   where b.id = any(v_build_ids) and b.status = 'draft' and b.user_id is null;
  if v_ready <> coalesce(array_length(v_build_ids, 1), 0) then
    return jsonb_build_object('error', 'builds_changed');
  end if;

  -- Claimed FIRST, so refuse_held_username() no longer sees the handle as
  -- held when the profile takes it two statements below.
  update public.creator_invites
     set status = 'claimed', claimed_at = now(), claimed_by = p_user_id
   where id = v.id;

  update public.profiles
     set username                      = v.handle,
         onboarding_complete           = true,
         bio                           = coalesce(nullif(bio, ''), v.bio),
         instagram_url                 = coalesce(nullif(instagram_url, ''), v.instagram_url),
         youtube_url                   = coalesce(nullif(youtube_url, ''), v.youtube_url),
         builder_agreement_accepted    = true,
         builder_agreement_version     = p_agreement_version,
         builder_agreement_accepted_at = now()
   where id = p_user_id;

  update public.build_photos
     set user_id = p_user_id
   where build_id = any(v_build_ids);

  update public.builds
     set user_id                   = p_user_id,
         status                    = 'approved',
         legal_confirmed           = true,
         content_license_confirmed = true,
         confirmed_at              = now(),
         builder_agreement_version = p_agreement_version
   where id = any(v_build_ids)
     and status = 'draft' and user_id is null;
  get diagnostics v_moved = row_count;
  if v_moved <> coalesce(array_length(v_build_ids, 1), 0) then
    -- Raise, not return: a raise rolls back the invite and profile writes above.
    raise exception 'claim moved % of % builds', v_moved, coalesce(array_length(v_build_ids, 1), 0);
  end if;

  return jsonb_build_object('handle', v.handle, 'build_ids', to_jsonb(v_build_ids));
end;
$$;

-- Decline: delete the drafts (returning their storage paths so the Edge
-- Function can remove the files), wipe what we wrote about them, keep the
-- handle held so nobody else can pose as them.
create or replace function public.decline_creator_invite(p_token_hash text)
returns jsonb
language plpgsql
set search_path to ''
as $$
declare
  v public.creator_invites;
  v_paths text[];
  v_deleted int;
begin
  select * into v from public.creator_invites
   where token_hash = p_token_hash
   for update;
  if not found or v.status in ('revoked', 'declined') then
    return jsonb_build_object('error', 'invalid');
  end if;
  if v.status = 'claimed' then
    return jsonb_build_object('error', 'already_claimed', 'handle', v.handle);
  end if;
  -- An expired link may still say no. Saying no is always allowed.

  select coalesce(array_agg(x), '{}') into v_paths
    from (
      select ph.storage_path as x
        from public.build_photos ph
        join public.creator_invite_builds cib on cib.build_id = ph.build_id
        join public.builds b on b.id = ph.build_id
       where cib.invite_id = v.id and b.status = 'draft' and b.user_id is null
      union all
      select ph.thumb_path
        from public.build_photos ph
        join public.creator_invite_builds cib on cib.build_id = ph.build_id
        join public.builds b on b.id = ph.build_id
       where cib.invite_id = v.id and b.status = 'draft' and b.user_id is null
         and ph.thumb_path is not null
    ) s;

  -- build_photos rows go with the build (FK cascade); so do the
  -- creator_invite_builds rows.
  delete from public.builds b
   using public.creator_invite_builds cib
   where cib.build_id = b.id and cib.invite_id = v.id
     and b.status = 'draft' and b.user_id is null;
  get diagnostics v_deleted = row_count;

  update public.creator_invites
     set status = 'declined', declined_at = now(),
         display_name = null, bio = null, instagram_url = null, youtube_url = null
   where id = v.id;

  return jsonb_build_object('deleted_builds', v_deleted, 'storage_paths', to_jsonb(v_paths));
end;
$$;

